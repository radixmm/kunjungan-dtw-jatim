export type Lang = "id" | "en";

export function pickLang(acceptLanguage?: string | null): Lang {
  const first = (acceptLanguage || "").split(",").map((s) => s.trim().slice(0, 2).toLowerCase()).find(Boolean);
  return first === "id" || first === "ms" || first === "jv" || first === "su" || !first ? "id" : "en";
}

